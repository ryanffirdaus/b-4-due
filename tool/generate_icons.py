"""Generates every B4Due launcher and notification icon from one geometry.

The mark comes from the month summary on Beranda: a dark panel holding a
"$" in Sora ExtraBold, a lime progress bar and a lime check dot, on an ink
gradient (docs/DESIGN.md). This script is the only source: it writes the
Android vector drawables (adaptive foreground and background, the themed
monochrome icon and the status-bar icon) and renders the PNG fallbacks for
older Android, iOS and docs/images/icon-512.png.

    python -m pip install pillow fonttools
    python tool/generate_icons.py
"""
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
DRAWABLE = ROOT / 'android/app/src/main/res/drawable'
FONT = ROOT / 'assets/fonts/Sora-ExtraBold.ttf'

GRADIENT_START = '2A2538'  # soft ink, top left
GRADIENT_END = '0E0C14'  # ink (Palette.dark.background), bottom right
PANEL = '29233A'  # a lifted Palette.dark.surface, so it reads on the ink
PANEL_EDGE = '3D3654'
DOLLAR = 'F2EEFA'  # Palette.dark.textPrimary
LIME = 'B6F36B'  # AccentColors.lime
TRACK = '433B57'  # Palette.dark.outlineStrong
INK = '15121D'

# Geometry in the 108-unit adaptive-icon viewport. Everything sits inside
# the 72-unit circle launchers may mask the icon to.
VIEWPORT = 108
PANEL_BOX = (24, 30, 84, 77)  # left, top, right, bottom
PANEL_RADIUS = 11.5
DOLLAR_X, DOLLAR_BASELINE, DOLLAR_SIZE = 33.2, 55.8, 20.7
BAR = (32.2, 62.1, 59.8, 67.2)
BAR_TRACK = (63.2, 62.1, 75.8, 67.2)
BAR_RADIUS = 2.55
DOT = (73.5, 41.4, 6.2)  # cx, cy, r
CHECK = [(70.8, 42.2), (72.7, 44.1), (76.5, 40.4)]
CHECK_WIDTH = 2.1


def _num(v: float) -> str:
    return f'{v:.2f}'.rstrip('0').rstrip('.')


def _dollar_path() -> str:
    """The "$" glyph as an SVG path in viewport units."""
    font = TTFont(FONT)
    scale = DOLLAR_SIZE / font['head'].unitsPerEm
    glyphs = font.getGlyphSet()
    pen = SVGPathPen(glyphs, ntos=_num)
    glyphs[font.getBestCmap()[ord('$')]].draw(
        TransformPen(pen, (scale, 0, 0, -scale, DOLLAR_X, DOLLAR_BASELINE)),
    )
    return pen.getCommands()


def _rounded_rect(box, r) -> str:
    left, top, right, bottom = (_num(v) for v in box)
    lr, rr = _num(box[0] + r), _num(box[2] - r)
    tr, br = _num(box[1] + r), _num(box[3] - r)
    return (
        f'M{lr},{top} L{rr},{top} Q{right},{top} {right},{tr} '
        f'L{right},{br} Q{right},{bottom} {rr},{bottom} '
        f'L{lr},{bottom} Q{left},{bottom} {left},{br} '
        f'L{left},{tr} Q{left},{top} {lr},{top} Z'
    )


def _check_path() -> str:
    return 'M' + ' L'.join(f'{_num(x)},{_num(y)}' for x, y in CHECK)


def _circle(cx, cy, r) -> str:
    return (
        f'M{_num(cx - r)},{_num(cy)} a{_num(r)},{_num(r)} 0 1,0 {_num(2 * r)},0 '
        f'a{_num(r)},{_num(r)} 0 1,0 {_num(-2 * r)},0 Z'
    )


def _path(data: str, fill: str | None = None, stroke: str | None = None, width: float = 0) -> str:
    attrs = [f'android:pathData="{data}"']
    attrs.append(f'android:fillColor="#FF{fill}"' if fill else 'android:fillColor="#00000000"')
    if stroke:
        attrs += [
            f'android:strokeColor="#FF{stroke}"',
            f'android:strokeWidth="{_num(width)}"',
            'android:strokeLineCap="round"',
            'android:strokeLineJoin="round"',
        ]
    return '    <path\n        ' + '\n        '.join(attrs) + ' />\n'


def _vector(comment: str, body: str, *, size: int = 108, group: str = '') -> str:
    if group:
        body = f'    <group {group}>\n' + body.replace('\n    ', '\n        ').replace('    <path', '        <path', 1) + '    </group>\n'
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f'<!-- {comment}\n'
        '     Generated by tool/generate_icons.py; edit that script, not this file. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size}dp"\n    android:height="{size}dp"\n'
        f'    android:viewportWidth="{VIEWPORT}"\n    android:viewportHeight="{VIEWPORT}">\n'
        f'{body}</vector>\n'
    )


def write_vectors() -> None:
    dollar = _dollar_path()
    (DRAWABLE / 'ic_launcher_background.xml').write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Adaptive-icon background: soft ink to ink.\n'
        '     Generated by tool/generate_icons.py; edit that script, not this file. -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        '    android:width="108dp"\n    android:height="108dp"\n'
        '    android:viewportWidth="108"\n    android:viewportHeight="108">\n'
        '    <path android:pathData="M0,0h108v108h-108z">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient\n                android:type="linear"\n'
        '                android:startX="0"\n                android:startY="0"\n'
        '                android:endX="108"\n                android:endY="108"\n'
        f'                android:startColor="#FF{GRADIENT_START}"\n'
        f'                android:endColor="#FF{GRADIENT_END}" />\n'
        '        </aapt:attr>\n    </path>\n</vector>\n',
        encoding='utf-8',
        newline='\n',
    )
    (DRAWABLE / 'ic_launcher_foreground.xml').write_text(
        _vector(
            'Adaptive-icon foreground: the month-summary panel with a "$", a lime\n'
            '     progress bar and a lime check dot.',
            _path(_rounded_rect(PANEL_BOX, PANEL_RADIUS), fill=PANEL, stroke=PANEL_EDGE, width=1)
            + _path(dollar, fill=DOLLAR)
            + _path(_rounded_rect(BAR, BAR_RADIUS), fill=LIME)
            + _path(_rounded_rect(BAR_TRACK, BAR_RADIUS), fill=TRACK)
            + _path(_circle(*DOT), fill=LIME)
            + _path(_check_path(), stroke=INK, width=CHECK_WIDTH),
        ),
        encoding='utf-8',
        newline='\n',
    )

    def silhouette(outline: float) -> str:
        return (
            _path(_rounded_rect(PANEL_BOX, PANEL_RADIUS), stroke='FFFFFF', width=outline)
            + _path(dollar, fill='FFFFFF')
            + _path(_rounded_rect(BAR, BAR_RADIUS), fill='FFFFFF')
            + _path(_circle(*DOT), fill='FFFFFF')
        )

    (DRAWABLE / 'ic_launcher_monochrome.xml').write_text(
        _vector(
            'Themed icon (Android 13+): only the alpha channel is used, so the\n'
            '     panel is an outline around the "$", the bar and the dot.',
            silhouette(3.5),
        ),
        encoding='utf-8',
        newline='\n',
    )

    # The status-bar icon reuses the silhouette, scaled up around the
    # viewport centre so the panel fills most of the 24dp square.
    left, top, right, bottom = PANEL_BOX
    zoom = (VIEWPORT - 8) / (right - left)
    cx, cy = (left + right) / 2, (top + bottom) / 2
    (DRAWABLE / 'ic_stat_b4due.xml').write_text(
        _vector(
            'Status bar icon: the B4Due mark as a white silhouette on transparent\n'
            '     (Android tints it with the notification colour).',
            silhouette(4.5),
            size=24,
            group=(
                f'android:pivotX="{_num(cx)}" android:pivotY="{_num(cy)}" '
                f'android:scaleX="{_num(zoom)}" android:scaleY="{_num(zoom)}" '
                f'android:translateX="{_num(VIEWPORT / 2 - cx)}" '
                f'android:translateY="{_num(VIEWPORT / 2 - cy)}"'
            ),
        ),
        encoding='utf-8',
        newline='\n',
    )


def _rgb(hex_colour: str, alpha: int = 255) -> tuple:
    return tuple(int(hex_colour[i:i + 2], 16) for i in (0, 2, 4)) + (alpha,)


def _gradient(s: int) -> Image.Image:
    start, end = _rgb(GRADIENT_START), _rgb(GRADIENT_END)
    img = Image.new('RGBA', (s, s))
    px = img.load()
    for y in range(s):
        for x in range(s):
            t = (x + y) / (2 * (s - 1))
            px[x, y] = tuple(round(a + (b - a) * t) for a, b in zip(start[:3], end[:3])) + (255,)
    return img


def render(size: int, *, rounded: bool, zoom: float = 1.3) -> Image.Image:
    """[zoom] enlarges the mark: PNG icons have no adaptive-icon mask to
    respect, so it can fill more of the square."""
    scale = 4  # supersample for smooth edges
    s = size * scale
    u = s / VIEWPORT * zoom
    offset = (s - VIEWPORT * u) / 2

    img = _gradient(s)
    if rounded:
        mask = Image.new('L', (s, s), 0)
        ImageDraw.Draw(mask).rounded_rectangle((0, 0, s - 1, s - 1), radius=int(s * 0.22), fill=255)
        img.putalpha(mask)
    d = ImageDraw.Draw(img)

    def p(v):
        return offset + v * u

    def box(b):
        return tuple(p(v) for v in b)

    d.rounded_rectangle(
        box(PANEL_BOX), radius=PANEL_RADIUS * u, fill=_rgb(PANEL),
        outline=_rgb(PANEL_EDGE), width=max(1, round(u)),
    )
    font = ImageFont.truetype(str(FONT), max(1, round(DOLLAR_SIZE * u)))
    d.text((p(DOLLAR_X), p(DOLLAR_BASELINE)), '$', font=font, fill=_rgb(DOLLAR), anchor='ls')
    d.rounded_rectangle(box(BAR), radius=BAR_RADIUS * u, fill=_rgb(LIME))
    d.rounded_rectangle(box(BAR_TRACK), radius=BAR_RADIUS * u, fill=_rgb(TRACK))
    cx, cy, r = DOT
    d.ellipse((p(cx - r), p(cy - r), p(cx + r), p(cy + r)), fill=_rgb(LIME))
    points = [(p(x), p(y)) for x, y in CHECK]
    width = CHECK_WIDTH * u
    d.line(points, fill=_rgb(INK), width=int(width), joint='curve')
    for x, y in points:
        d.ellipse((x - width / 2, y - width / 2, x + width / 2, y + width / 2), fill=_rgb(INK))

    return img.resize((size, size), Image.LANCZOS)


def main() -> None:
    write_vectors()

    android = ROOT / 'android/app/src/main/res'
    for density, px in {'mdpi': 48, 'hdpi': 72, 'xhdpi': 96, 'xxhdpi': 144, 'xxxhdpi': 192}.items():
        render(px, rounded=True).save(android / f'mipmap-{density}/ic_launcher.png')

    ios = ROOT / 'ios/Runner/Assets.xcassets/AppIcon.appiconset'
    for png in ios.glob('*.png'):
        with Image.open(png) as existing:
            px = existing.size[0]
        # iOS applies its own mask and rejects transparency.
        render(px, rounded=False).convert('RGB').save(png)

    docs = ROOT / 'docs/images'
    docs.mkdir(parents=True, exist_ok=True)
    render(512, rounded=True).save(docs / 'icon-512.png')
    print('icons written')


if __name__ == '__main__':
    main()
